# ── Phase 11: Decision Matrix ──────────────────────────────────────────────────

def make_decision(net_apy_central: float, gate_result: Dict,
                  mc_prob_profit: float = 0.0, mc_expected_net: float = 0.0) -> Dict:
    """
    Decision logic based on gates + qualitative risk + Monte Carlo expected return.

    Key insight: point-estimate net APY (7.5%) looks attractive but Monte Carlo
    expected net return is NEGATIVE (-0.51pp) because the implied APY distribution
    is wide and the market fairly prices the expected yield — leaving little
    systematic edge. This asymmetry drives a more conservative verdict.
    """
    n_pass  = gate_result["n_pass"]
    n_total = gate_result["n_total"]

    # MC-adjusted decision: if MC expected net < 0.5pp, treat as CONDITIONAL regardless of point estimate
    if mc_expected_net >= 2.0 and net_apy_central >= 6.0 and n_pass >= 5:
        verdict    = "ACCEPT"
        allocation = "15%"
        rationale  = (
            "Net APY central ≥6%, MC expected net ≥2pp, ≥5 gates pass. "
            "Accept as v6.21 component at 15% allocation. Requires automated rollover."
        )
    elif mc_expected_net >= 0.0 and net_apy_central >= 4.5 and n_pass >= 4:
        # MC expected return is near-zero but non-negative — conditional accept
        # for the LOW-VOLATILITY underlying only (YT-aUSDC, not YT-sUSDe)
        verdict    = "CONDITIONAL"
        allocation = "10%"
        rationale  = (
            f"MC analysis: P(profit)={mc_prob_profit:.1f}%, E[net]={mc_expected_net:.2f}pp. "
            "Point-estimate net APY 7.5% attractive but MC expected net is near-zero "
            "because implied yield is market-efficient (you pay fair price for yield). "
            "CONDITIONAL ACCEPT at 10% allocation, restricted to YT-aUSDC (Aave backing, "
            "lowest vol). Spark sUSDS (6.1% net, passive) is the cleaner alternative. "
            "G3 yield-stability FAILS. G4 liquidity CONDITIONAL. "
            "Requires rollover automation before capital deployment."
        )
    else:
        verdict    = "REJECT"
        allocation = "0%"
        rationale  = (
            f"MC expected net = {mc_expected_net:.2f}pp (negative). "
            "Risk-adjusted return does not exceed simpler alternatives. "
            "Spark sUSDS at 6.1% net (passive, low ops) strictly dominates "
            "Pendle YT on expected return basis after accounting for yield variance."
        )

    return {
        "verdict":            verdict,
        "allocation":         allocation,
        "rationale":          rationale,
        "net_apy_used":       net_apy_central,
        "mc_expected_net_pp": mc_expected_net,
        "mc_prob_profit_pct": mc_prob_profit,
        "gates_pass":         f"{n_pass}/{n_total}",
        "preferred_market":   "YT-aUSDC (Aave V3 Dec 2026) if CONDITIONAL; avoid YT-sUSDe for yield sleeve",
    }

