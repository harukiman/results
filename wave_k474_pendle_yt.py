# ── Phase 2: PT/YT Mechanics ──────────────────────────────────────────────────

def yt_price(underlying_price: float, pt_price: float) -> float:
    """YT = SY - PT conceptually (not literal formula, illustrative)."""
    return underlying_price - pt_price


def implied_apy(yt_price_usd: float, pt_price_usd: float, days_to_maturity: float) -> float:
    """
    Implied APY from Pendle docs:
      implied_apy = (1 + yt_price / pt_price) ^ (365 / days_to_maturity) - 1
    """
    if days_to_maturity <= 0 or pt_price_usd <= 0:
        return 0.0
    ratio = yt_price_usd / pt_price_usd
    return (1 + ratio) ** (365.0 / days_to_maturity) - 1


def yt_time_decay(initial_yt_value: float, days_remaining: float, total_days: float) -> float:
    """
    Linear time-decay model: YT decays ~linearly to 0 at maturity under constant implied yield.
    yt_value(t) = initial_yt_value * (days_remaining / total_days)
    """
    if total_days <= 0:
        return 0.0
    return initial_yt_value * (days_remaining / total_days)


